#!/bin/bash
set -euo pipefail
lab_dir="$(cd "$(dirname "$0")" && pwd)"
project_dir="$(dirname "$lab_dir")"
runtime="$(command -v node)"
destination="$1"
test ! -e "$destination"
source_app="$lab_dir/shell/node_modules/electron/dist/Electron.app"
test -d "$source_app"
mkdir -p "$(dirname "$destination")"
ditto "$source_app" "$destination"
metadata="$destination/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleIdentifier digital.akimov.doop-stacki-test" "$metadata"
/usr/libexec/PlistBuddy -c "Set :CFBundleName Doop + Stacki Test" "$metadata"
/usr/libexec/PlistBuddy -c "Set :CFBundleDisplayName Doop + Stacki Test" "$metadata"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString 0.2.0" "$metadata"
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion 2" "$metadata"
resources="$destination/Contents/Resources"
mkdir "$resources/app"
cp "$lab_dir/shell/"{package.json,main.mjs,preload.cjs,studio-preload.cjs,index.html,shell.css,shell.js} "$resources/app/"
node -e 'require("node:fs").writeFileSync(process.argv[1],JSON.stringify({root:process.argv[2],node:process.argv[3]}))' "$resources/app/paths.json" "$project_dir" "$runtime"
codesign --force --deep --sign - "$destination"
codesign --verify --deep --strict "$destination"
